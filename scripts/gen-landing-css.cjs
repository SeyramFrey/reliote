// Temporary generator: ports the design prototype's CSS into a scoped landing stylesheet.
// Reads index-print.html, strips parts already covered by globals.css, scopes everything
// under `.rl`, and rewrites @keyframes names to `rl-*` so they can't clobber Tailwind's.
const fs = require("fs");
const path = require("path");

const SRC = path.join(
  __dirname,
  "..",
  "_design-reference",
  "reliote",
  "project",
  "index-print.html"
);
const OUT = path.join(__dirname, "..", "src", "styles", "landing.css");

const html = fs.readFileSync(SRC, "utf8");
const styleMatch = html.match(/<style>([\s\S]*?)<\/style>/);
if (!styleMatch) throw new Error("No <style> block found");
let css = styleMatch[1];

// 1. Drop everything from `@media print` to the end (print export only; would nest @page).
const printIdx = css.indexOf("@media print");
if (printIdx !== -1) css = css.slice(0, printIdx);

// 2. Drop the leading reset + helper classes (already provided by globals.css):
//    everything before the first component block (`/* Header */`).
const headerIdx = css.indexOf("/* Header */");
if (headerIdx !== -1) css = css.slice(headerIdx);

// 3. Scope the one bare element rule so it can't affect <section> app-wide.
css = css.replace(
  /\bsection\s*\{\s*position:\s*relative;\s*\}/,
  ".sect { position: relative; }"
);

// 4. Public assets are served from /assets at runtime — not bundled relative to the CSS.
css = css.replace(/url\((["']?)assets\//g, "url($1/assets/");

// 3. Extract @keyframes blocks (one level of nested braces for the % stops), rename to rl-*.
const keyframeNames = [];
const keyframeBlocks = [];
css = css.replace(
  /@keyframes\s+([\w-]+)\s*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g,
  (block, name) => {
    keyframeNames.push(name);
    keyframeBlocks.push(block.replace(/@keyframes\s+[\w-]+/, `@keyframes rl-${name}`));
    return "";
  }
);

// 4. Rename the `animation:`/`animation-name:` references to the renamed keyframes.
//    Longest names first so `t-pulse` doesn't partially match `t-pulse-dot`.
const sorted = [...new Set(keyframeNames)].sort((a, b) => b.length - a.length);
for (const name of sorted) {
  const re = new RegExp(`(animation(?:-name)?\\s*:\\s*)${name}\\b`, "g");
  css = css.replace(re, `$1rl-${name}`);
}

const ALIAS = `:root {
  --green:        var(--color-green);
  --green-deep:   var(--color-green-deep);
  --green-soft:   var(--color-green-soft);
  --accent-brass: var(--color-brass);
  --paper:        var(--color-paper);
  --paper-2:      var(--color-paper-2);
  --ink:          var(--color-ink);
  --ink-2:        var(--color-ink-2);
  --concrete-1:   var(--color-concrete-1);
  --concrete-2:   var(--color-concrete-2);
  --concrete-3:   var(--color-concrete-3);
  --concrete-4:   var(--color-concrete-4);
  --water:        var(--color-water);
  --f-display:    var(--font-display);
  --f-sans:       var(--font-sans);
  --f-mono:       var(--font-mono);
}
`;

const header = `/* Reliote landing — ported from the design prototype (index-print.html).
 * Generated by scripts/gen-landing-css.cjs. Reset + helper classes are dropped (they live
 * in globals.css); class names are unique to the landing design (verified no collisions in
 * src), so the rules are emitted globally. Design tokens are aliased to globals.css above. */

`;

const out =
  header +
  ALIAS +
  "\n/* Keyframes (top-level; renamed rl-* to avoid clobbering Tailwind's `pulse`). */\n" +
  keyframeBlocks.join("\n") +
  "\n\n" +
  css.trim() +
  "\n";

fs.writeFileSync(OUT, out, "utf8");
console.log(
  `Wrote ${OUT}\n  ${out.length} bytes, ${out.split("\n").length} lines, keyframes: ${sorted.join(", ")}`
);
